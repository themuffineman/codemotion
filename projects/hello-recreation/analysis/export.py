import numpy as np, cv2, json
from common import *
c,L=resample(cr(json.load(open('apple_pts.json'))),2); n=len(c)
ok=np.ones(n,bool)
for i in range(n):
    d=np.linalg.norm(c-c[i],axis=1); far=np.abs(np.arange(n)-i)>30
    if (d[far]<44).any(): ok[i]=False
im=cv2.imread('../hello/frames/f147.png').astype(float)[:,:,::-1]
pr=np.array([im[y-3:y+4,x-3:x+4].reshape(-1,3).mean(0) for x,y in c.round().astype(int)])
s=np.arange(n)*2.0
# boost to palette-like brightness: normalise so max channel ~ like hello palette
grid=np.arange(0,L,10)
cols=[]
for ch in range(3):
    xs=np.r_[s[ok]-L,s[ok],s[ok]+L]; ys=np.tile(pr[ok,ch],3)
    cols.append(np.interp(grid,xs,ys))
cols=np.stack(cols,1)
k=np.ones(5)/5
cols=np.stack([np.convolve(np.r_[cols[-2:,i],cols[:,i],cols[:2,i]],k,'valid') for i in range(3)],1)
json.dump({'length':L,'step':10,'colors':['#%02x%02x%02x'%tuple(int(min(255,round(v))) for v in p) for p in cols]},open('apple_colors.json','w'))
pal=json.load(open('palette.json'))
out='''// Measured from the original clip (1280x720 coordinates). Generated by the analysis scripts.
export const HELLO_POINTS: [number, number][] = %s;
export const APPLE_POINTS: [number, number][] = %s;
/** Looping colour pattern along the hello tube, sampled every `step` px of arc length (1280 scale). */
export const HELLO_PALETTE = %s;
/** Colour along the Apple tube at its resting frame (146), every `step` px of arc length. */
export const APPLE_COLORS = %s;
''' % (json.dumps(json.load(open('hello_pts.json'))), json.dumps(json.load(open('apple_pts.json'))), json.dumps(pal), json.dumps(json.load(open('apple_colors.json'))))
open('measured.ts','w').write(out)
print(len(out), pr[ok].max(0))
